LENGTHS = {"t1": 5, "t2": 15, "t3": 25}


def main() -> None:
    assert len(SLIDES) == 25
    for bid, n in LENGTHS.items():
        b = {"lang": "Japanese", "look": DENSE_JA, "slides": SLIDES[:n]}
        d = HERE / bid
        d.mkdir(exist_ok=True)
        (d / "brief.md").write_text(brief_md(f"lengthbench-{bid}", b), encoding="utf-8")
        (d / "accept.json").write_text(
            json.dumps(accept(b), ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
        print(bid, n, "slides")


if __name__ == "__main__":
    main()
